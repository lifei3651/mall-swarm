    public boolean applyDefaults(DmsTenant tenant) {
        if (tenant == null) return false;
        boolean changed = false;
        if (isBlank(tenant.getServiceHours())) {
            tenant.setServiceHours(DEFAULT_SERVICE_HOURS);
            changed = true;
        }
        if (isBlank(tenant.getThirdPartyServices())) {
            tenant.setThirdPartyServices(DEFAULT_THIRD_PARTY_SERVICES);
            changed = true;
        }
        if (isBlank(tenant.getUserAgreement())) {
            tenant.setUserAgreement(USER_AGREEMENT);
            changed = true;
        }
        if (isBlank(tenant.getPrivacyPolicy())) {
            tenant.setPrivacyPolicy(PRIVACY_POLICY);
            changed = true;
        }
        if (isBlank(tenant.getAfterSalePolicy())) {
            tenant.setAfterSalePolicy(AFTER_SALE_POLICY);
            changed = true;
        }
        return changed;
    }

    private boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
