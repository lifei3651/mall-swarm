import { createHash } from 'node:crypto'
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { resolve, join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const vendor = resolve(scriptDir, '../vendor/payload-crypto')
const version = '1.4.0'
const integrity = 'sha512-LarFH0+6VfriEhqMMcLX2F7SwSXeWwnEAJEsYm5QKWchiVYVvJyV9v7UDvUv+w5HO23ZpQTXDv/GxdDdMyOuoQ=='
const compilerVersion = '0.28.2'
const source = `https://registry.npmjs.org/node-forge/-/node-forge-${version}.tgz`
const temp = await mkdtemp(join(tmpdir(), 'mall-payload-crypto-build-'))
const response = await fetch(source)
if (!response.ok) throw new Error(`Source download failed (${response.status})`)
const archive = Buffer.from(await response.arrayBuffer())
if (`sha512-${createHash('sha512').update(archive).digest('base64')}` !== integrity) throw new Error('node-forge archive integrity mismatch')
const archivePath = join(temp, 'forge.tgz')
await writeFile(archivePath, archive)
const files = execFileSync('tar', ['-tzf', archivePath], { encoding: 'utf8' }).trim().split('\n')
if (files.some((path) => !path.startsWith('package/') || path.split('/').includes('..'))) throw new Error('Unsafe dependency archive paths')
// Build tools are installed only into this freshly created temporary directory, with lifecycle scripts disabled.
execFileSync('npm', ['install', '--prefix', temp, '--no-save', '--package-lock=false', '--ignore-scripts', '--no-audit', '--no-fund', '--registry=https://registry.npmjs.org', `esbuild@${compilerVersion}`], { stdio: 'pipe' })
await mkdir(join(temp, 'node_modules/node-forge'), { recursive: true })
execFileSync('tar', ['-xzf', archivePath, '--strip-components=1', '-C', join(temp, 'node_modules/node-forge')])
const require = createRequire(join(temp, 'entry.cjs'))
const esbuild = require('esbuild')
await mkdir(vendor, { recursive: true })
const output = join(vendor, 'index.js')
await esbuild.build({
  entryPoints: [join(scriptDir, 'payload-crypto/entry.js')], outfile: output,
  nodePaths: [join(temp, 'node_modules')], bundle: true, minify: true, format: 'cjs', platform: 'browser', target: 'es2017',
  define: { 'process.browser': 'true', 'process.versions': 'undefined', 'Math.random': '__forbiddenRandom' },
  banner: { js: `/* node-forge ${version}; BSD-3-Clause. Generated by scripts/build-payload-crypto.mjs. */\nvar self = typeof globalThis !== 'undefined' ? globalThis : {};\nfunction __forbiddenRandom() { throw new Error('Non-cryptographic randomness is disabled'); }` },
  plugins: [{ name: 'block-implicit-randomness', setup(build) {
    build.onResolve({ filter: /(?:^|\/)random(?:\.js)?$/ }, () => ({ path: join(scriptDir, 'payload-crypto/no-random.js') }))
    build.onResolve({ filter: /^crypto$/ }, () => ({ path: 'disabled-node-crypto', namespace: 'disabled' }))
    build.onLoad({ filter: /.*/, namespace: 'disabled' }, () => ({ contents: 'module.exports = {}', loader: 'js' }))
  } }]
})
const built = await readFile(output)
// Preserve all upstream license text, normalizing only trailing blank lines.
const licenseText = await readFile(join(temp, 'node_modules/node-forge/LICENSE'), 'utf8')
await writeFile(join(vendor, 'LICENSE'), licenseText.replace(/\n+$/, '\n'))
await writeFile(join(vendor, 'SOURCE.json'), JSON.stringify({
  name: 'node-forge', version, source, integrity, license: 'BSD-3-Clause', compiler: `esbuild@${compilerVersion}`,
  sha256: createHash('sha256').update(built).digest('hex'), bytes: built.length,
  repository: 'https://github.com/digitalbazaar/forge',
  regeneration: 'node mall-mini-program/scripts/build-payload-crypto.mjs',
  restrictions: 'Only RSA-OAEP SHA256/MGF1-SHA256 and AES-256-GCM are exposed. Default forge PRNG is replaced with a fail-closed stub; all entropy must be supplied by wx.getRandomValues.'
}, null, 2) + '\n')
console.log(`Verified and bundled node-forge ${version}: ${built.length} bytes; ${createHash('sha256').update(built).digest('hex')}`)
